-- =============================================================================
-- 5. slot_number backfill for legacy timeslot rows
--    (deterministic: order by start_time within each day, appended after the
--    current max slot_number for that day so no collisions can occur)
-- =============================================================================

UPDATE timeslots t
SET slot_number = sub.rn
FROM (
    SELECT t.id,
           (SELECT COALESCE(MAX(d.slot_number), 0)
              FROM timeslots d
             WHERE d.day = t.day AND d.slot_number IS NOT NULL)
           + ROW_NUMBER() OVER (PARTITION BY t.day ORDER BY t.start_time, t.id) AS rn
      FROM timeslots t
     WHERE t.slot_number IS NULL
) sub
WHERE t.id = sub.id;
