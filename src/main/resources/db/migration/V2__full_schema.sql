-- V2: Full baseline schema.
-- -----------------------------------------------------------------------------
-- Single source of truth for the physical schema. The application runs with
-- spring.jpa.hibernate.ddl-auto=validate, and V1 contains no CREATE TABLE
-- statements, so a brand-new database used to have no tables and the app
-- could not boot. This migration creates the complete schema.
--
-- Idempotent for BOTH fresh and existing (legacy Hibernate-created) databases:
--   * CREATE TABLE IF NOT EXISTS  - legacy tables are skipped as-is
--   * FK constraints are name-guarded (PostgreSQL has no ADD CONSTRAINT IF NOT
--     EXISTS, so each FK is added inside a pg_constraint existence check)
--   * unique indexes use CREATE UNIQUE INDEX IF NOT EXISTS
-- -----------------------------------------------------------------------------

