-- NOTE: timeslots intentionally does NOT declare a unique constraint on
-- (day, slot_number). Multi-slot ordering must allow rows with NULL
-- slot_number; uniqueness for populated slot numbers is enforced by the
-- partial unique index uk_timeslots_day_slot_number below.
CREATE TABLE IF NOT EXISTS timeslots (
    end_time time(6) not null,
    slot_number integer,
    start_time time(6) not null,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    updated_at timestamp(6) not null,
    version bigint not null,
    day varchar(255) not null check (day in ('MONDAY','TUESDAY','WEDNESDAY','THURSDAY','FRIDAY','SATURDAY')),
    type varchar(255) not null check (type in ('CLASS','BREAK','BLOCKED')),
    primary key (id),
    unique (day, start_time, end_time)
);

CREATE TABLE IF NOT EXISTS university_configs (
